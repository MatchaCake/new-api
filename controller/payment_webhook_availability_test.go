func TestEpayCallbacksVerifyBeforeSettlement(t *testing.T) {
	confirmPaymentComplianceForTest(t)
	originalPayAddress := operation_setting.PayAddress
	originalEpayID := operation_setting.EpayId
	originalEpayKey := operation_setting.EpayKey
	originalPayMethods := operation_setting.PayMethods
	originalServerAddress := system_setting.ServerAddress
	originalDB := model.DB
	t.Cleanup(func() {
		operation_setting.PayAddress = originalPayAddress
		operation_setting.EpayId = originalEpayID
		operation_setting.EpayKey = originalEpayKey
		operation_setting.PayMethods = originalPayMethods
		system_setting.ServerAddress = originalServerAddress
		model.DB = originalDB
	})
	operation_setting.PayAddress = "https://pay.example.com"
	operation_setting.EpayId = "epay_id"
	operation_setting.EpayKey = "test-key"
	operation_setting.PayMethods = []map[string]string{{"type": "alipay"}}
	system_setting.ServerAddress = "https://dashboard.example.com"
	// Rejected callbacks and valid non-success events must never reach settlement.
	// A nil database makes an accidental attempt to settle fail the test.
	model.DB = nil
	require.True(t, isEpayWebhookEnabled())

	// Both ambiguous maps below had this same valid signing string in v0.0.4.
	// This must fail because of parameter ambiguity, not a mismatched signature.
	ambiguousSign := epay.MD5String("money=1.00&name=item&out_trade_no=other&out_trade_no=order&pid=epay_id&trade_status=TRADE_SUCCESS&type=alipay", "test-key")
	pendingSign := epay.MD5String("money=1.00&name=item%26other&out_trade_no=order&pid=epay_id&trade_status=WAIT_BUYER_PAY&type=alipay", "test-key")
	cases := []struct {
		name         string
		productName  string
		tradeNo      string
		status       string
		sign         string
		validPending bool
	}{
		{"separator in product name", "item&out_trade_no=other", "order", epay.StatusTradeSuccess, ambiguousSign, false},
		{"separator in order number", "item", "other&out_trade_no=order", epay.StatusTradeSuccess, ambiguousSign, false},
		{"invalid signature", "item", "order", epay.StatusTradeSuccess, "invalid", false},
		{"missing signature", "item", "order", epay.StatusTradeSuccess, "", false},
		{"valid pending with literal percent escape", "item%26other", "order", "WAIT_BUYER_PAY", pendingSign, true},
	}
	endpoints := []struct {
		name             string
		path             string
		handler          gin.HandlerFunc
		status           int
		rejectedBody     string
		pendingBody      string
		rejectedLocation string
		pendingLocation  string
	}{
		{
			name: "topup notify", path: "/api/user/epay/notify", handler: EpayNotify,
			status: http.StatusOK, rejectedBody: "fail", pendingBody: "success",
		},
		{
			name: "subscription notify", path: "/api/subscription/epay/notify", handler: SubscriptionEpayNotify,
			status: http.StatusOK, rejectedBody: "fail", pendingBody: "fail",
		},
		{
			name: "subscription return", path: "/api/subscription/epay/return", handler: SubscriptionEpayReturn,
			status:           http.StatusFound,
			rejectedLocation: "https://dashboard.example.com/wallet?pay=fail",
			pendingLocation:  "https://dashboard.example.com/wallet?pay=pending",
		},
	}
	router := gin.New()
	for _, endpoint := range endpoints {
		router.Any(endpoint.path, endpoint.handler)
	}
	for _, endpoint := range endpoints {
		for _, method := range []string{http.MethodGet, http.MethodPost} {
			for _, tc := range cases {
				t.Run(endpoint.name+"/"+method+"/"+tc.name, func(t *testing.T) {
					params := url.Values{
						"pid": {"epay_id"}, "type": {"alipay"}, "money": {"1.00"},
						"name": {tc.productName}, "out_trade_no": {tc.tradeNo},
						"trade_status": {tc.status}, "sign_type": {"MD5"},
					}
					if tc.sign != "" {
						params.Set("sign", tc.sign)
					}
					request := httptest.NewRequest(method, endpoint.path+"?"+params.Encode(), nil)
					if method == http.MethodPost {
						request = httptest.NewRequest(method, endpoint.path, strings.NewReader(params.Encode()))
						request.Header.Set("Content-Type", "application/x-www-form-urlencoded")
					}
					recorder := httptest.NewRecorder()
					require.NotPanics(t, func() { router.ServeHTTP(recorder, request) })
					assert.Equal(t, endpoint.status, recorder.Code)
					wantBody, wantLocation := endpoint.rejectedBody, endpoint.rejectedLocation
					if tc.validPending {
						wantBody, wantLocation = endpoint.pendingBody, endpoint.pendingLocation
					}
					if wantBody != "" {
						assert.Equal(t, wantBody, recorder.Body.String())
					}
					assert.Equal(t, wantLocation, recorder.Header().Get("Location"))
				})
			}
		}
	}
}

func TestEpayV2NotifySettlesOnlyVerifiedMatchingCallbacks(t *testing.T) {
	confirmPaymentComplianceForTest(t)
	originals := []string{operation_setting.PayAddress, operation_setting.EpayId, operation_setting.EpayKey,
		operation_setting.EpayVersion, operation_setting.EpayMerchantPrivateKey, operation_setting.EpayPlatformPublicKey}
	originalPayMethods := operation_setting.PayMethods
	t.Cleanup(func() {
		operation_setting.PayAddress, operation_setting.EpayId, operation_setting.EpayKey = originals[0], originals[1], originals[2]
		operation_setting.EpayVersion, operation_setting.EpayMerchantPrivateKey, operation_setting.EpayPlatformPublicKey = originals[3], originals[4], originals[5]
		operation_setting.PayMethods = originalPayMethods
	})

	merchantKey, err := rsa.GenerateKey(rand.Reader, 2048)
	require.NoError(t, err)
	platformKey, err := rsa.GenerateKey(rand.Reader, 2048)
	require.NoError(t, err)
	b64 := func(der []byte, err error) string {
		require.NoError(t, err)
		return base64.StdEncoding.EncodeToString(der)
	}

	operation_setting.PayAddress = "https://pay.example.com"
	operation_setting.EpayId = "7071"
	operation_setting.EpayKey = ""
	operation_setting.PayMethods = []map[string]string{{"type": "alipay"}}
	operation_setting.EpayVersion = "v2"
	operation_setting.EpayMerchantPrivateKey = b64(x509.MarshalPKCS8PrivateKey(merchantKey))
	operation_setting.EpayPlatformPublicKey = ""
	require.False(t, isEpayWebhookEnabled(), "v2 requires both RSA keys")
	require.Nil(t, GetEpayClient())
	operation_setting.EpayPlatformPublicKey = b64(x509.MarshalPKIXPublicKey(&platformKey.PublicKey))
	require.True(t, isEpayWebhookEnabled(), "v2 does not need the V1 MD5 key")
	_, isV2 := GetEpayClient().(*epayv2.Client)
	require.True(t, isV2)

	db := setupModelListControllerTestDB(t)
	require.NoError(t, db.AutoMigrate(&model.User{}, &model.TopUp{}, &model.Log{}))
	require.NoError(t, db.Create(&model.User{Id: 1, Username: "alice", Quota: 0}).Error)
	require.NoError(t, db.Create(&model.TopUp{UserId: 1, Amount: 10, Money: 73, TradeNo: "USR1NOv2", PaymentMethod: "alipay",
		PaymentProvider: model.PaymentProviderEpay, Status: common.TopUpStatusPending}).Error)

	gateway, err := epayv2.NewClient("7071", "https://pay.example.com", b64(x509.MarshalPKCS8PrivateKey(platformKey)), b64(x509.MarshalPKIXPublicKey(&merchantKey.PublicKey)))
	require.NoError(t, err)
	callback := func(money string, tamper func(url.Values)) string {
		params := map[string]string{"pid": "7071", "trade_no": "P1", "out_trade_no": "USR1NOv2", "type": "alipay",
			"trade_status": epay.StatusTradeSuccess, "name": "TUC10", "money": money, "timestamp": "1721206072"}
		sign, err := gateway.Sign(params)
		require.NoError(t, err)
		values := url.Values{"sign": {sign}, "sign_type": {"RSA"}}
		for k, v := range params {
			values.Set(k, v)
		}
		if tamper != nil {
			tamper(values)
		}
		recorder := httptest.NewRecorder()
		router := gin.New()
		router.GET("/api/user/epay/notify", EpayNotify)
		router.ServeHTTP(recorder, httptest.NewRequest(http.MethodGet, "/api/user/epay/notify?"+values.Encode(), nil))
		return recorder.Body.String()
	}
	status := func() string { return model.GetTopUpByTradeNo("USR1NOv2").Status }

	assert.Equal(t, "fail", callback("73.00", func(v url.Values) { v.Set("money", "0.01") }), "tampered after signing")
	assert.Equal(t, "fail", callback("0.01", nil), "validly signed but underpaid")
	assert.Equal(t, common.TopUpStatusPending, status())

	assert.Equal(t, "success", callback("73.00", nil))
	assert.Equal(t, common.TopUpStatusSuccess, status())
	assert.Equal(t, "success", callback("73.00", nil), "duplicate callback is acknowledged")
	user, err := model.GetUserById(1, true)
	require.NoError(t, err)
	assert.Equal(t, int(10*common.QuotaPerUnit), user.Quota, "credited exactly once")
}
